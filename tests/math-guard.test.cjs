'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const Guard = require('../public/cultivation/math-guard.js');
const { questionQualityIssue } = require('../question-quality.cjs');
const math = fs.readFileSync(path.join(__dirname, '../public/cultivation/quiz-math.js'), 'utf8');
const main = fs.readFileSync(path.join(__dirname, '../public/main.js'), 'utf8');

test('math guard accepts valid inline/display TeX, ordinary CJK and escaped dollars', () => {
  for (const source of [
    'x < 3 且 A&B',
    String.raw`設 \(x^2+\frac{1}{2}\) 求值`,
    String.raw`$\frac{1}{2}$`,
    String.raw`$$\begin{aligned}x&=2\\y&=3\end{aligned}$$`,
    String.raw`\[ \left(\frac{1}{2}\right)^2 \]`,
    String.raw`價格是 \$50 美元`
  ]) assert.equal(Guard.inspect(source).valid, true, source);
});

test('math guard rejects unmatched math delimiters, braces and TeX environments', () => {
  for (const source of [
    String.raw`公式 \(x^2+1`,
    String.raw`$x^{2$`,
    String.raw`$$\frac{1}{2}$`,
    String.raw`\( \left(x+1 \)`,
    String.raw`\[\begin{aligned}x=1\end{cases}\]`,
    String.raw`x \)`
  ]) assert.equal(Guard.inspect(source).valid, false, source);
});

test('math error fallback is escaped, ignored by MathJax, and keeps raw source readable', () => {
  const invalid = String.raw`<script>x</script> \(x^2`;
  const markup = Guard.fallback(invalid);
  assert.match(markup, /tex2jax_ignore/);
  assert.match(markup, /&lt;script&gt;/);
  assert.doesNotMatch(markup, /<script>/);
  assert.match(markup, /\\\(x\^2/);
});

test('AI generated questions are rejected if any option or solution contains broken math', () => {
  const good = { q: String.raw`計算 \(\frac12+1\)`,
    correct: String.raw`\(\frac32\)`, wrong: ['1', '2', '0'],
    exp: String.raw`計算得到 \(\frac32\)` };
  assert.equal(questionQualityIssue(good), '');
  assert.match(questionQualityIssue({ ...good, exp: String.raw`因為 \(x^{2\)` }), /數學公式/);
  assert.match(questionQualityIssue({ ...good, wrong: ['1', '2', String.raw`$x`] }), /數學公式/);
});

test('shared MathJax renderer is guarded and a malformed expression stays legible', () => {
  const context = { window: { QAMathGuard: Guard }, console };
  vm.runInNewContext(math, context);
  const rich = context.window.quizMathRichText;
  const wrong = String.raw`設 \(x^2+1`;
  assert.match(rich(wrong), /quiz-math-fallback/);
  assert.match(rich(wrong), /tex2jax_ignore/);
  const valid = String.raw`\(x^2+1\)`;
  assert.equal(rich(valid), valid);
  const ix = p => main.indexOf("'" + p + "'");
  assert.ok(ix('./cultivation/math-guard.js') >= 0);
  assert.ok(ix('./cultivation/math-guard.js') < ix('./cultivation/quiz-math.js'));
});

test('MathJax merror is turned into readable text; a typeset exception does not break future questions', async () => {
  const errors = [], mock = {
    startup: { promise: Promise.resolve() },
    typesetClear() {},
    async typesetPromise(roots) {
      for (const node of roots) {
        if (node.innerHTML.includes('BAD')) node.hasError = true;
        if (node.innerHTML.includes('THROW')) throw Error('renderer broke');
      }
    }
  };
  const context = { window: { QAMathGuard: Guard, MathJax: mock },
    console: { warn(...args) { errors.push(args); } } };
  vm.runInNewContext(math, context);
  function node(source = 'BAD') {
    return { isConnected: true, innerHTML: '', textContent: source,
      querySelector(selector) { return this.hasError ? {} : null; } };
  }
  const bad = node();
  await context.window.quizMathSet(bad, 'BAD');
  assert.match(bad.innerHTML, /tex2jax_ignore/);
  const thrown = node('THROW');
  await context.window.quizMathSet(thrown, 'THROW');
  assert.match(thrown.innerHTML, /tex2jax_ignore/);
  assert.match(thrown.innerHTML, /THROW/);
  const good = node('valid formula');
  await context.window.quizMathSet(good, 'VALID');
  assert.equal(good.innerHTML, 'VALID');
  assert.ok(errors.length >= 1);
});


test('literal Math input error generated by MathJax is replaced with original formula', async () => {
  const context = { window: { QAMathGuard: Guard, MathJax: {
    startup: { promise: Promise.resolve() }, typesetClear() {},
    async typesetPromise(nodes) {
      for (const node of nodes) { node.textContent = 'Math input error'; node.renderedMath = true; }
    }
  } }, console };
  vm.runInNewContext(math, context);
  const node = { isConnected: true, innerHTML: '', textContent: 'original formula',
    querySelector(selector) {
      return this.renderedMath && selector.includes('mjx-container') ? {} : null;
    } };
  await context.window.quizMathSet(node, '$\\badcommand$');
  assert.match(node.innerHTML, /tex2jax_ignore/);
  assert.match(node.innerHTML, /original formula/);
  assert.doesNotMatch(node.innerHTML, /Math input error/);
});


test('literal slash-n, slash-r, slash-t and unicode escapes display as readable prose', () => {
  const prose = String.raw`第一行\n第二行\r\n第三行\t縮排\u03C0\u{1F600}\x3C`;
  assert.equal(Guard.expandTextEscapes(prose), '第一行\n第二行\n第三行\u3000縮排π😀<');
  assert.equal(Guard.expandTextEscapes(String.raw`引號\"測試與路徑\/test`), '引號"測試與路徑/test');
  assert.equal(Guard.expandTextEscapes('第一行\n第二行'), '第一行\n第二行');
  assert.equal(Guard.expandTextEscapes(Guard.expandTextEscapes(prose)), Guard.expandTextEscapes(prose));
  assert.match(Guard.fallback(prose), /第一行<br>第二行<br>/);
  assert.match(Guard.fallback(prose), /π😀&lt;/);
});

test('escaped prose must not corrupt LaTeX control sequences or escaped backslashes', () => {
  const source = String.raw`解答\n計算 \( \nu+\neq+\nabla+\theta+\times+\text{a\nb} \)\n$$\begin{aligned}x&=1\\y&=2\end{aligned}$$`;
  const output = Guard.expandTextEscapes(source);
  assert.ok(output.startsWith('解答\n計算 '));
  assert.ok(output.includes(String.raw`\nu+\neq+\nabla+\theta+\times+\text{a\nb}`));
  assert.ok(output.includes(String.raw`\begin{aligned}x&=1\\y&=2\end{aligned}`));
  assert.equal(Guard.inspect(output).valid, true);
  assert.equal(Guard.expandTextEscapes(String.raw`字面 \\n 字串`), String.raw`字面 \\n 字串`);
  assert.equal(Guard.expandTextEscapes(String.raw`價格 \$50 且 \frac{1}{2}`),
    String.raw`價格 \$50 且 \frac{1}{2}`);
});

test('live question and legacy rich text both apply serialized special escapes safely', () => {
  const legacy = fs.readFileSync(path.join(__dirname, '../public/main-legacy.js'), 'utf8');
  const begin = legacy.indexOf('function normalizeQuizSymbols(');
  const finish = legacy.indexOf('window.formatQuizRichText = formatQuizRichText;', begin);
  assert.ok(begin >= 0 && finish > begin);
  const context = { window: { QAMathGuard: Guard },
    escapeHtml: text => Guard.escape(text), console };
  vm.runInNewContext(legacy.slice(begin, finish + 'window.formatQuizRichText = formatQuizRichText;'.length), context);
  const rich = context.window.formatQuizRichText;
  const source = String.raw`步驟一\n計算 \(\frac{1}{2}\)\n步驟二\uFF1Cscript\uFF1E`;
  const output = rich(source);
  assert.match(output, /步驟一<br>計算 /);
  assert.ok(output.includes(String.raw`\(\frac{1}{2}\)`));
  assert.match(output, /<br>步驟二/);
  assert.doesNotMatch(output, /<script>/);
  const context2 = { window: { QAMathGuard: Guard, formatQuizRichText: rich }, console };
  vm.runInNewContext(math, context2);
  assert.equal(context2.window.quizMathRichText(source), output);
});
